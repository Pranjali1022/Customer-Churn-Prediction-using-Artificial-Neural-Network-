import streamlit as st
import numpy as np
import tensorflow as tf
from sklearn.preprocessing import StandardScaler, LabelEncoder, OneHotEncoder
import pandas as pd
import pickle

model= tf.keras.models.load_model('model.h5')

#load the scaler and encoder
with open("onehot_encoder_geo.pkl", 'rb') as file:
  onehot_encoder_geo=pickle.load(file)

with open("label_encoder_gender.pkl", 'rb') as file:
  label_encoder_gender=pickle.load(file)

with open("scaler.pkl", 'rb') as file:
  scaler=pickle.load(file)

st.title("Customer Churn Prediction")

geography=st.selectbox('Geography', onehot_encoder_geo.categories_[0])
gender=st.selectbox('Gender', label_encoder_gender.classes_)
age=st.number_input('Age', 18, 92)
balance=st.number_input('Balance')
credit_score=st.number_input('Credit Score')
tenure=st.number_input('Tenure', 0, 10)
num_of_products=st.number_input('Number of Products', 1, 4)
has_cr_card=st.selectbox('Has Credit Card', ['No', 'Yes'])
has_cr_card = 1 if has_cr_card== 'Yes' else 0
is_active_member=st.selectbox('Is Active Member', ['No', 'Yes'])
is_active_member = 1 if is_active_member== 'Yes' else 0
estimated_salary=st.number_input('Estimated Salary')

input_data=pd.DataFrame({
    'CreditScore':[credit_score],
    'Age':[age],
    'Gender':[label_encoder_gender.transform([gender])[0]],
    'Tenure':[tenure],
    'Balance':[balance],
    'NumOfProducts':[num_of_products],
    'HasCrCard':[has_cr_card],
    'IsActiveMember':[is_active_member],
    'EstimatedSalary':[estimated_salary]
})

geo_encoded=onehot_encoder_geo.transform([[geography]]).toarray()
geo_encoded_df=pd.DataFrame(geo_encoded,columns=onehot_encoder_geo.get_feature_names_out())

input_data=pd.concat([input_data.reset_index(drop=True), geo_encoded_df], axis=1)

input_data_scaled=scaler.transform(input_data[scaler.feature_names_in_])

input_data_scaled

st.markdown("---") 
if st.button('Predict Churn'):
    prediction = model.predict(input_data_scaled)
    prediction_proba = prediction[0][0]

    st.subheader(f"Churn Probability: {prediction_proba:.2%}")
    
    if prediction_proba > 0.5:
        st.error("The customer is likely to churn.")
    else:
        st.success("The customer is not likely to churn.")

